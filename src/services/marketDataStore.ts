// Search filter implementation
export function searchStocksLocally(query: string): StockQuote[] {
  if (!query || !query.trim()) return [];
  const q = query.trim().toUpperCase();
  return ALL_QUOTES_LIST.filter(stock => {
    return (
      stock.symbol.toUpperCase().includes(q) ||
      stock.name.toUpperCase().includes(q) ||
      stock.sector.toUpperCase().includes(q) ||
      stock.exchange.toUpperCase().includes(q)
    );
  });
}
